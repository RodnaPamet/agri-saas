/**
 * The ONE translation from `.secret-patterns` to a JS `RegExp` — #2578.
 *
 * `.secret-patterns` is this repo's single source of truth for secret
 * detection, loaded today by `scripts/detect-secrets.sh` (the pre-commit hook)
 * and `tests/guardrails/no-secrets.test.ts` (the C.2 guardrail). The egress
 * control the assistant needs is a third consumer, and it runs in the SERVER.
 *
 * ## Why this exists as a module rather than inline in the generator
 *
 * A second copy of a selection rule is how two answers diverge — the reason
 * `scripts/lib/api-routes.ts` is shared by the route generator and its test,
 * and `scripts/lib/coverage-groups.mjs` is held once for the checker and the
 * differ. The generator and the sync guard both need this translation, so it
 * lives in one place they both import.
 *
 * NOTE a second implementation of this translation still exists, inline in
 * `tests/guardrails/no-secrets.test.ts`. That is pre-existing and deliberately
 * untouched here: it is a C.2 guardrail, and rewiring it to read a GENERATED
 * file would make a stale generated file able to weaken it. Unifying the two
 * wants its own change.
 */

/**
 * PCRE → `{ source, flags }`.
 *
 * The pattern file uses the PCRE syntax `grep -P` accepts. Node's `RegExp`
 * takes everything used here once the inline modifier is lifted to the flag
 * set: measured on the live file, 12 of 14 patterns compile unchanged and the
 * 2 that do not fail only on a leading `(?i)`.
 *
 * Hoisting `(?i)` to the `i` flag is equivalent ONLY when it is at the start,
 * because PCRE scopes an inline modifier from where it appears. Both live
 * occurrences are at index 0 — verified — and a mid-pattern one would WIDEN
 * the match, so it is refused rather than hoisted.
 */
export function translatePattern(name, pcre) {
    const at = pcre.indexOf('(?i)');
    if (at > 0) {
        throw new Error(
            `Pattern "${name}" has an inline (?i) at index ${at}, not at the start. `
                + `PCRE scopes it from that point, so lifting it to the flag set would `
                + `WIDEN the match. Rewrite the pattern with the modifier leading, or `
                + `make it explicitly case-sensitive.`,
        );
    }
    const flags = at === 0 ? 'i' : '';
    const source = at === 0 ? pcre.slice(4) : pcre;
    // Compile here so a bad pattern fails the GENERATOR rather than the server.
    new RegExp(source, flags);
    return { source, flags };
}

/**
 * Parse the whole file. Mirrors `no-secrets.test.ts`'s reader, including its
 * refusals: a malformed line throws, and an empty result throws — an empty
 * pattern set would make every scan report "clean", which is the
 * absence-reads-as-success shape.
 */
export function parseSecretPatterns(text) {
    const out = [];
    for (const raw of text.split(/\r?\n/)) {
        const line = raw.trim();
        if (!line || line.startsWith('#')) continue;
        const idx = line.indexOf('|');
        if (idx <= 0) {
            throw new Error(`Malformed line in .secret-patterns: ${JSON.stringify(raw)}`);
        }
        const name = line.slice(0, idx).trim();
        const { source, flags } = translatePattern(name, line.slice(idx + 1).trim());
        out.push({ name, source, flags });
    }
    if (out.length === 0) {
        throw new Error('No patterns parsed from .secret-patterns');
    }
    return out;
}

/** The committed module's text, so the generator and the guard cannot disagree. */
export function renderModule(patterns) {
    const rows = patterns
        .map((p) => `    { name: ${JSON.stringify(p.name)}, source: ${JSON.stringify(p.source)}, flags: ${JSON.stringify(p.flags)} },`)
        .join('\n');
    return `// GENERATED by scripts/generate-secret-patterns.mjs — do not edit.
//
// Source of truth: \`.secret-patterns\` at the repo root. Run
// \`npm run secret-patterns:generate\` after changing it;
// \`tests/guards/secret-patterns-generated-in-sync.test.ts\` fails CI on drift.
//
// ## Why this file exists at all
//
// \`.secret-patterns\` is NOT copied into the production image — the runner
// stage takes \`public\`, \`.next\`, \`node_modules\`, \`package.json\`, \`prisma\`,
// two scripts, \`dist\` and the PDF fonts, and nothing else. A server-side
// \`readFileSync('.secret-patterns')\` therefore throws ENOENT in production
// while passing every test, and the shared reader throws on an empty set, so
// the egress control would crash the route or be caught and fail OPEN. Green
// in CI, wrong in the image — #929's shape.
//
// Generated into a module instead, so it is bundled and reaches the place it
// has to work. Same arrangement as \`design/tokens.json\` → \`tokens.css\`.

export interface SecretPattern {
    readonly name: string;
    readonly source: string;
    readonly flags: string;
}

export const SECRET_PATTERNS: readonly SecretPattern[] = [
${rows}
] as const;
`;
}
