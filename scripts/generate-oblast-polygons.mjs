#!/usr/bin/env node
/**
 * Generate `src/lib/geo/oblast-polygons.generated.ts` from
 * `public/geo/bg-oblasti.geojson` — #3100.
 *
 * ## Why generated and not read at runtime
 *
 * `public/geo/README.md` states that file is a STATIC ASSET, "never fetched
 * at runtime and never stored in the DB". Both halves of that are load-bearing
 * and neither is mine to overturn: `public/` is served to browsers rather than
 * imported, and the data is third-party CC-BY-4.0, which is why it was kept
 * out of the database in the first place.
 *
 * So the rings are emitted as a TypeScript module that only SERVER code
 * imports. `tokens:check` is the pattern: generate, commit, and verify in CI
 * that the committed output still matches its source — because regenerating
 * the artefact and its checksum in one step makes a changed input a green
 * diff, which is the `fonts:vendor` lesson.
 *
 * ## Precision is 3 decimal places, deliberately
 *
 * ~111 m at this latitude, against oblasti ~100 km across. The only points it
 * can misclassify are within ~111 m of an oblast boundary, and the only ones
 * that matter for the north/south question are within ~111 m of THAT line
 * specifically. A farmer there overrides the picker; the alternative is 60 KB
 * for 1 m precision nobody can use.
 *
 * Usage:
 *   node scripts/generate-oblast-polygons.mjs            # write
 *   node scripts/generate-oblast-polygons.mjs --check    # verify, exit 1 on drift
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { resolve, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const SOURCE = resolve(ROOT, 'public/geo/bg-oblasti.geojson');
const TARGET = resolve(ROOT, 'src/lib/geo/oblast-polygons.generated.ts');
const DP = 3;

function build() {
    const gj = JSON.parse(readFileSync(SOURCE, 'utf8'));
    const feats = gj.features ?? [];
    if (feats.length !== 28) {
        throw new Error(`expected 28 ADM1 features, found ${feats.length} — refusing to generate`);
    }
    const rows = [];
    for (const f of feats) {
        const iso = f.properties?.shapeISO;
        if (!/^BG-\d\d$/.test(iso ?? '')) {
            throw new Error(`feature has no BG-nn shapeISO: ${JSON.stringify(f.properties)}`);
        }
        // Every feature in this release is a single-ring Polygon (verified:
        // 28 Polygons, 1 ring each). A MultiPolygon or a hole would need the
        // ray-cast caller to change, so refuse rather than silently drop part
        // of a province.
        if (f.geometry?.type !== 'Polygon') {
            throw new Error(`${iso}: expected Polygon, got ${f.geometry?.type}`);
        }
        if (f.geometry.coordinates.length !== 1) {
            throw new Error(
                `${iso}: ${f.geometry.coordinates.length} rings — the ray cast assumes one, `
                + `so a hole would be silently ignored`,
            );
        }
        const ring = f.geometry.coordinates[0].map(([lon, lat]) => [
            Number(lon.toFixed(DP)),
            Number(lat.toFixed(DP)),
        ]);
        rows.push([iso, ring]);
    }
    rows.sort((a, b) => (a[0] < b[0] ? -1 : 1));

    const body = rows
        .map(([iso, ring]) => `    '${iso}': [${ring.map(([x, y]) => `[${x},${y}]`).join(',')}],`)
        .join('\n');

    return `/**
 * GENERATED by \`scripts/generate-oblast-polygons.mjs\` — do not edit.
 *
 * The 28 Bulgarian oblast boundaries from \`public/geo/bg-oblasti.geojson\`
 * (geoBoundaries gbOpen BGR ADM1, CC-BY-4.0 — attribution: geoBoundaries,
 * Runfola et al. 2020), rounded to ${DP} decimal places (~111 m).
 *
 * SERVER-ONLY by intent. It is ~48 KB of coordinates; a client module that
 * imported it would ship all of them to every phone. \`agro-region.ts\` is the
 * only consumer and is reached from the locations DTO, which no client module
 * imports.
 *
 * Regenerate with \`npm run geo:oblasts\`; \`npm run geo:oblasts:check\`
 * verifies the committed copy against the source and is what CI runs.
 */

/** Closed outer ring per oblast, \`[lon, lat]\`, keyed by ISO 3166-2:BG code. */
export const OBLAST_RINGS: Readonly<Record<string, readonly (readonly [number, number])[]>> = {
${body}
};

/** The ISO codes, sorted — the generator's own population, for a floor. */
export const OBLAST_CODES: readonly string[] = Object.keys(OBLAST_RINGS);
`;
}

const next = build();
if (process.argv.includes('--check')) {
    let current = '';
    try {
        current = readFileSync(TARGET, 'utf8');
    } catch {
        console.error(`[geo:oblasts] ${TARGET} is missing — run \`npm run geo:oblasts\``);
        process.exit(1);
    }
    if (current !== next) {
        console.error(
            '[geo:oblasts] the committed module does NOT match public/geo/bg-oblasti.geojson.\n'
            + 'Run `npm run geo:oblasts` and commit the result.',
        );
        process.exit(1);
    }
    // Counted from the OUTPUT, so the number printed is the number the app
    // will load rather than a constant that happens to agree with it.
    const count = (next.match(/^\s+'BG-\d\d': \[/gm) ?? []).length;
    console.log(`[geo:oblasts] in sync — ${count} oblast ring(s)`);
} else {
    writeFileSync(TARGET, next);
    console.log(`[geo:oblasts] wrote ${TARGET} (${(next.length / 1024).toFixed(1)} KB)`);
}
