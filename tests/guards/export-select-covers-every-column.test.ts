/** `promotionLead` → `PromotionLead`, the delegate spelling Prisma generates. */
function delegateName(model: string): string {
    return model[0].toLowerCase() + model.slice(1);
}

/**
 * Every key that appears in ANY `select` for a delegate, anywhere in the file.
 *
 * Nested `select` blocks are flattened away before keys are read, so a
 * relation's columns are not counted as the parent's. The union is the whole
 * point — see the docblock.
 */
export function selectedColumnsByDelegate(raw: string): Map<string, Set<string>> {
    // Comments AND strings blanked, character-for-character — see the
    // docblock. A `// attachmentMime: true,` left behind by somebody disabling
    // a column must not read as that column being exported.
    const source = blankNonCode(raw, { strings: true });
    const found = new Map<string, Set<string>>();
    const call = /(?:prisma|db|tx)\.([a-zA-Z][A-Za-z0-9]*)\.(?:findMany|findUnique|findFirst|findUniqueOrThrow)\(\{/g;
    let match: RegExpExecArray | null;
    while ((match = call.exec(source)) !== null) {
        const delegate = match[1];
        const selectAt = source.indexOf('select: {', match.index);
        if (selectAt < 0) continue;

        // Balance braces from the opening one, so a nested object does not end
        // the block early.
        let depth = 0;
        let body = '';
        for (let i = selectAt + 'select: '.length; i < source.length; i += 1) {
            const ch = source[i];
            if (ch === '{') depth += 1;
            else if (ch === '}') {
                depth -= 1;
                if (depth === 0) break;
            }
            body += ch;
        }

        let flat = body.slice(1);
        let previous: string;
        do {
            previous = flat;
            flat = flat.replace(/\{[^{}]*\}/g, '');
        } while (flat !== previous);

        const keys = [...flat.matchAll(/([A-Za-z_][A-Za-z0-9_]*)\s*:/g)].map((k) => k[1]);
        if (!found.has(delegate)) found.set(delegate, new Set());
        const set = found.get(delegate)!;
        keys.forEach((k) => set.add(k));
    }
    return found;
}

describe('the Art 15 export covers every column of an exported model (#2840)', () => {
    const source = readFileSync(EXPORT_SOURCE, 'utf8');
    const selected = selectedColumnsByDelegate(source);
    const models = Prisma.dmmf.datamodel.models;
    const byName = new Map(models.map((m) => [m.name, m]));

    /**
     * `User` is NOT in the registry and its columns ARE exported.
     *
     * The registry classifies models whose rows belong to a person; the `User`
     * row itself is the special case P5.6b rules on — it SURVIVES erasure
     * under Art 17(3)(b) so a moderation history stays answerable, with the
     * identifying content pseudonymised. It has no registry entry at all, and
     * `exportPersonalData` reads it into the `account` block, so an Art 15
     * population derived from `EXPORTED_MODELS` alone would skip the one model
     * every export contains. Nine of the unreviewed columns below live here,
     * and so do the three the credential rule exists for — without `User` that
     * rule matches nothing and §5 says so.
     */
    const POPULATION = [...EXPORTED_MODELS, 'User'];

    /** `Model.column` for every scalar or enum column of an exported model. */
    const everyColumn: string[] = [];
    for (const name of POPULATION) {
        const model = byName.get(name);
        if (!model) continue;
        for (const field of model.fields) {
            if (field.kind === 'scalar' || field.kind === 'enum') {
                everyColumn.push(`${name}.${field.name}`);
            }
        }
    }

    const omitted = (qualified: string): boolean => qualified in OMITTED_BY_DECISION;

    const isSelected = (qualified: string): boolean => {
        const [model, column] = qualified.split('.');
        return selected.get(delegateName(model))?.has(column) ?? false;
    };
    const exemptRule = (qualified: string) =>
        EXEMPT_BY_RULE.find((r) => r.test.test(qualified.split('.')[1]));

    it('§0 EXTRACTION CONTROL — the parser finds the selects it is reading', () => {
        // Without this the whole guard passes over nothing: a renamed helper, a
        // reformatted call or a change of quoting style empties the extraction,
        // and every column then appears "unselected" OR — if the model list
        // also emptied — nothing is checked at all. Both directions are floored.
        expect(selected.size).toBeGreaterThanOrEqual(19);
        expect(everyColumn.length).toBeGreaterThanOrEqual(150);
        // And the union is real: `PromotionLead.requestMessage` is selected
        // ONLY by the second, tenant-bound query, so a first-match scan misses
        // it. This is the assertion that fails if somebody "simplifies" the
        // extraction back.
        expect(isSelected('PromotionLead.requestMessage')).toBe(true);
    });

    it('§0b a COMMENTED-OUT or quoted key is not a selected column', () => {
        // The control for the blanking, on a synthetic source rather than the
        // real file, because the real file has no commented-out select line —
        // and a protection is invisible while nothing violates it.
        const synthetic = `
            prisma.directMessage.findMany({
                select: {
                    id: true,
                    // attachmentMime: true,
                    /* linkTitle: true, */
                    label: 'linkDescription: true',
                    body: true,
                },
            });
        `;
        const keys = selectedColumnsByDelegate(synthetic).get('directMessage')!;
        expect([...keys].sort()).toEqual(['body', 'id', 'label']);
        expect(keys.has('attachmentMime')).toBe(false);
        expect(keys.has('linkTitle')).toBe(false);
        expect(keys.has('linkDescription')).toBe(false);
    });

    it('§1 reports its denominator', () => {
        const sel = everyColumn.filter(isSelected).length;
        const ruled = everyColumn.filter((c) => !isSelected(c) && exemptRule(c)).length;
        const left = everyColumn.length - sel - ruled;
        console.log(
            `[art15-export-columns] ${everyColumn.length} column(s) across `
            + `${POPULATION.length} exported model(s): ${sel} selected, `
            + `${ruled} exempt by rule, ${left} omitted by decision `
            + `(the map holds ${Object.keys(OMITTED_BY_DECISION).length})`,
        );
        // EQUAL, not `<=`. The unreviewed bucket is gone (#2863), so every
        // column is now accounted for by a selection, a rule or a written
        // refusal — and slack here would let the next unreviewed column hide
        // under a decision somebody else made.
        expect(left).toBe(Object.keys(OMITTED_BY_DECISION).length);
    });

    it('§2 every column is selected, exempt by rule, or on the baseline', () => {
        const unaccounted = everyColumn.filter(
            (c) => !isSelected(c) && !exemptRule(c) && !omitted(c),
        );
        expect(unaccounted).toEqual([]);
    });

    it('§3 no refusal is stale — cover expires with the fix', () => {
        const gone = Object.keys(OMITTED_BY_DECISION).filter((c) => {
            const [model, column] = c.split('.');
            const m = byName.get(model);
            // Outside the POPULATION counts as gone, not as covered. An entry
            // for a model this guard does not grade is cover nothing consults,
            // which stays alive for whatever is created at that name next —
            // and it is how the `User.*` entries read as fine while the whole
            // model sat outside the check.
            if (!POPULATION.includes(model)) return true;
            return !m || !m.fields.some((f) => f.name === column);
        });
        const nowSelected = Object.keys(OMITTED_BY_DECISION).filter(isSelected);
        const ruled = Object.keys(OMITTED_BY_DECISION).filter((c) => exemptRule(c));
        // A refusal is COVER. One for a column that was since exported, or
        // that a rule now exempts, keeps that cover alive for whatever is
        // created at the same name next — the #1285 failure.
        expect({ gone, nowSelected, ruled }).toEqual({ gone: [], nowSelected: [], ruled: [] });
        // And every refusal states a REASON, long enough to be one.
        for (const why of Object.values(OMITTED_BY_DECISION)) {
            expect(why.length).toBeGreaterThan(100);
        }
    });

    it('§4b the person\'s OWN data reaches the export — #2863\'s ruling', () => {
        // NAMED, not derived: these are the columns the ruling turned from
        // "unreviewed" into "exported", and the starkest of them is the reason
        // the issue existed — a seller's own listing exported with its
        // commodity and description and NO price, quantity or region.
        for (const column of [
            'ExchangeListing.quantityTonnes', 'ExchangeListing.pricePerTonne',
            'ExchangeListing.regionName', 'ExchangeListing.sellerContact',
            'ExchangeInquiry.inquirerContact', 'ExchangeThread.inquirerLastReadAt',
            'User.image', 'User.newsTagPreferences', 'User.deletionRequestedAt',
            'AssistantMemoryFact.supersededAt', 'ContentReport.alertedAt',
        ]) {
            expect(isSelected(column)).toBe(true);
        }
        // And the line the ruling drew holds in the other direction: the
        // counterparty's read cursor is NOT exported, though its sibling is.
        expect(isSelected('ExchangeThread.sellerLastReadAt')).toBe(false);
        expect(omitted('ExchangeThread.sellerLastReadAt')).toBe(true);
    });

    it('§4 the DM attachment and link columns reach the export — #2840 itself', () => {
        // Named rather than derived, because this is the defect: eight columns
        // landed and the select omitted all eight. `attachmentKey` is the one
        // deliberate omission and sits on the baseline.
        for (const column of [
            'attachmentMime', 'attachmentBytes', 'attachmentSha256',
            'linkUrl', 'linkTitle', 'linkDescription', 'linkFetchedAt',
        ]) {
            expect(isSelected(`DirectMessage.${column}`)).toBe(true);
        }
    });

    it('§5 every exemption rule carries a written reason', () => {
        for (const rule of EXEMPT_BY_RULE) {
            expect(rule.why.length).toBeGreaterThan(60);
        }
        // And each rule must actually exempt something, or it is a pattern that
        // no longer matches the schema — a rule matching nothing is the shape
        // `a-number-that-does-not-move` warns about.
        for (const rule of EXEMPT_BY_RULE) {
            const hits = everyColumn.filter(
                (c) => !isSelected(c) && rule.test.test(c.split('.')[1]),
            );
            expect(hits.length).toBeGreaterThan(0);
        }
    });
});
