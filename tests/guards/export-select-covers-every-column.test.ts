/**
 * Art 15 — every column of an exported model either REACHES the export or has
 * a reason not to (#2840).
 *
 * `personal-data-registry-complete` holds the other axis: which MODELS are
 * exported, derived from the DMMF, so a new tenantless table holding a person
 * id has to be classified. It was green throughout the defect this guard
 * exists for, and correctly — the registry's own principle is "ONE registry,
 * two consumers", and that holds for models. **Nothing held it for columns.**
 *
 * `exportPersonalData` reads every model with an EXPLICIT `select`, and an
 * explicit list is a list that goes stale. P8.6 added eight columns to
 * `DirectMessage` and the select omitted all eight, so a photo-only message
 * exported as a row with a null body and nothing else — an empty message
 * rather than a photograph. That is the second time an explicit select has
 * been the weak link here: #1597 shipped five WRONG column names in this file
 * which typechecked clean, because `tsc` does not validate a `select` key
 * against the DMMF on the extended client.
 *
 * ## What this guard reads, and the mistake it was built around
 *
 * It unions EVERY `select` in the file per model, not the first one. The first
 * draft read only the first and reported `PromotionLead.requestMessage` as
 * missing — while `export-decrypts-promotion-lead.test.ts` was passing, which
 * is how the error surfaced. That column is deliberately absent from the
 * privileged read and fetched by a SECOND, tenant-bound query (its `v2:`
 * envelope is under a per-tenant DEK a tenantless read cannot resolve), then
 * merged into the row. A union sees both; a first-match scan reports a defect
 * that is not there. **The contradicting passing test is what caught it.**
 *
 * ## What it CANNOT see, stated so it is not assumed
 *
 * This is a SOURCE guard: it proves a column reaches a `select`, not that it
 * reaches the person. A column selected and then dropped before the envelope
 * would pass here. The behavioural half is `tests/integration/p5-6a-export`
 * and the two export suites beside it, which run the real function and read
 * the rows it returns. Neither subsumes the other — a source guard covers
 * every model including the ones no fixture seeds, and a runtime test covers
 * the merge this guard can only approximate.
 */
import { Prisma } from '@prisma/client';
import { readFileSync } from 'fs';
import { join } from 'path';

import { EXPORTED_MODELS } from '@/lib/privacy/personal-data-registry';

const EXPORT_SOURCE = join(process.cwd(), 'src/app-layer/usecases/personal-data-export.ts');

/**
 * Columns excluded by a RULE rather than one at a time.
 *
 * A predicate per reason, not 24 strings: the reasons are categorical, and a
 * per-column list of them would be 24 places to forget rather than one. Each
 * carries the reason it is not personal data the person is owed, and anything
 * matching none of them has to be decided individually below.
 */
const EXEMPT_BY_RULE: readonly { readonly test: RegExp; readonly why: string }[] = [
    {
        test: /^(?:[a-z][A-Za-z0-9]*)?[Uu]serId$/,
        why:
            'A person id. Every row in this export is already selected BY this '
            + 'person, so their own id repeated per row tells them nothing — and '
            + 'where the column names somebody ELSE (createdByUserId, '
            + 'recipientUserId) it is another person\'s identity and must not be '
            + 'exported at all.',
    },
    {
        test: /^(?:emailHash|passwordHash|sessionVersion)$/,
        why:
            'A credential or a lookup derivation. #1597\'s ruling: a live token '
            + 'in a downloadable file is a leak and answers nothing the person '
            + 'asked, and `emailHash` hands out the input to a correlation attack '
            + 'against any other system using the same HMAC.',
    },
    {
        test: /^(?:clientMutationId|idempotencyKey)$/,
        why:
            'A client replay key. Opaque, generated by the caller\'s own device '
            + 'to deduplicate a re-send, and information about a transport rather '
            + 'than about a person.',
    },
    {
        test: /^updatedAt$/,
        why:
            'Row bookkeeping. `createdAt` is exported everywhere because when '
            + 'something happened is the person\'s information; when a row was '
            + 'last touched by the system is not.',
    },
    {
        test: /^actionId$/,
        why:
            'The moderation action behind a statement of reasons. P5.6a\'s ruling: '
            + 'the statement itself IS exported because it was written to them, and '
            + '`actionId` is the join onto another party\'s rationale.',
    },
];

/**
 * Columns NOT YET REVIEWED against Art 15 — #2863.
 *
 * SHRINK-ONLY. Measured 2026-11-08 by running this guard's own extraction: 176
 * columns across 19 exported models, 107 reaching a select, 24 exempt by the
 * rules above, and these left over. They are NOT a decision that they may be
 * withheld — they are the ones nobody has decided about, which is a different
 * thing, and the reason this list is named for an open issue rather than given
 * a reason each.
 *
 * Some are plainly the person's own (`ExchangeListing.pricePerTonne`, so a
 * seller's listing exports without its price; `User.image`;
 * `ExchangeInquiry.inquirerContact`). Some are farm or internal ids where the
 * answer is arguable. All of them need the same review, and adding ~38 columns
 * to a legal export is not a change to make silently on the way past.
 *
 * **An entry here is cover, so it expires:** §3 fails when a baseline entry
 * names a column that no longer exists or has since been selected, so the cover
 * is removed in the same diff as the fix.
 */
